-- A atribuição do cliente ao afiliado é comissionável: sem esta trava o
-- cliente poderia se desvincular ou apontar para outro afiliado e roubar
-- os pontos do pedido.
create or replace function public.fn_customers_guard_referral()
returns trigger
language plpgsql
as $$
begin
  if current_user not in ('authenticated', 'anon') or public.is_admin() then
    return new;
  end if;

  if new.id is distinct from old.id
     or new.referred_by is distinct from old.referred_by then
    raise exception 'Alteração não permitida: o vínculo com o afiliado é gerido pelo sistema';
  end if;

  return new;
end;
$$;

drop trigger if exists customers_guard_referral on public.customers;
create trigger customers_guard_referral
  before update on public.customers
  for each row execute function public.fn_customers_guard_referral();

