-- =============================================================
-- 005 — Loja integrada
-- Admin cadastra produtos; o cliente (conta própria) faz o pedido;
-- o pedido cai na fila do admin, que entra em contato e fecha a venda.
-- Não há pagamento online: o fechamento é manual.
--
-- Clientes ficam em `customers`, e não em `users`, de propósito:
-- `users` é a árvore de afiliados e carrega triggers de recrutamento (3x),
-- ciclo mensal e graduação. Um cliente nessa tabela geraria pontos de
-- recrutamento e entraria no fechamento mensal.
-- =============================================================

do $$ begin
  create type public.order_status as enum ('novo', 'em_contato', 'fechado', 'cancelado');
exception when duplicate_object then null; end $$;

-- -------------------------------------------------------------
-- Clientes finais
-- -------------------------------------------------------------
create table if not exists public.customers (
  id          uuid primary key references auth.users (id) on delete cascade,
  full_name   text not null,
  email       text,
  phone       text,
  address     text,
  -- afiliado que trouxe o cliente (link da loja)
  referred_by uuid references public.users (id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists customers_referred_by_idx on public.customers (referred_by);

drop trigger if exists customers_touch_updated_at on public.customers;
create trigger customers_touch_updated_at
  before update on public.customers
  for each row execute function public.fn_touch_updated_at();

-- -------------------------------------------------------------
-- Catálogo
-- price_cents evita erro de arredondamento de ponto flutuante
-- points_value é quanto a venda deste produto injeta na rede
-- -------------------------------------------------------------
create table if not exists public.products (
  id           uuid primary key default gen_random_uuid(),
  name         text not null,
  description  text,
  sku          text unique,
  price_cents  int  not null check (price_cents >= 0),
  points_value int  not null default 0 check (points_value >= 0),
  image_url    text,
  is_active    boolean not null default true,
  sort_order   int not null default 0,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index if not exists products_active_idx on public.products (is_active, sort_order);

drop trigger if exists products_touch_updated_at on public.products;
create trigger products_touch_updated_at
  before update on public.products
  for each row execute function public.fn_touch_updated_at();

-- -------------------------------------------------------------
-- Pedidos
-- Totais e pontos são snapshots calculados no servidor no momento
-- do pedido — o cliente nunca envia preço nem pontuação.
-- -------------------------------------------------------------
create table if not exists public.orders (
  id            uuid primary key default gen_random_uuid(),
  order_number  bigint generated by default as identity,
  customer_id   uuid not null references public.customers (id) on delete cascade,
  -- snapshot do contato: o admin precisa ligar mesmo se o cliente editar o perfil
  contact_name  text not null,
  contact_phone text not null,
  contact_email text,
  address       text,
  customer_notes text,
  referred_by   uuid references public.users (id) on delete set null,
  status        public.order_status not null default 'novo',
  total_cents   int not null default 0 check (total_cents >= 0),
  total_points  int not null default 0 check (total_points >= 0),
  admin_notes   text,
  contacted_at  timestamptz,
  closed_at     timestamptz,
  cancelled_at  timestamptz,
  reviewed_by   uuid references public.users (id) on delete set null,
  created_at    timestamptz not null default now()
);

create unique index if not exists orders_order_number_idx on public.orders (order_number);
create index if not exists orders_status_idx      on public.orders (status, created_at desc);
create index if not exists orders_customer_idx    on public.orders (customer_id, created_at desc);
create index if not exists orders_referred_by_idx on public.orders (referred_by);

create table if not exists public.order_items (
  id               uuid primary key default gen_random_uuid(),
  order_id         uuid not null references public.orders (id) on delete cascade,
  product_id       uuid references public.products (id) on delete set null,
  -- snapshots: o histórico do pedido não muda se o produto for editado
  product_name     text not null,
  quantity         int  not null check (quantity between 1 and 999),
  unit_price_cents int  not null check (unit_price_cents >= 0),
  unit_points      int  not null check (unit_points >= 0),
  created_at       timestamptz not null default now()
);

create index if not exists order_items_order_idx on public.order_items (order_id);

