create or replace view public.v_admin_orders
with (security_invoker = true) as
select
  o.id,
  o.order_number,
  o.status,
  o.contact_name,
  o.contact_phone,
  o.contact_email,
  o.address,
  o.customer_notes,
  o.admin_notes,
  o.total_cents,
  o.total_points,
  o.created_at,
  o.contacted_at,
  o.closed_at,
  o.cancelled_at,
  o.customer_id,
  o.referred_by,
  u.username as referred_by_username,
  u.full_name as referred_by_name,
  (select count(*) from public.order_items i where i.order_id = o.id) as item_count,
  coalesce(
    (select jsonb_agg(jsonb_build_object(
       'product_name', i.product_name,
       'quantity', i.quantity,
       'unit_price_cents', i.unit_price_cents,
       'unit_points', i.unit_points
     ) order by i.product_name)
     from public.order_items i where i.order_id = o.id),
    '[]'::jsonb
  ) as items
from public.orders o
left join public.users u on u.id = o.referred_by
order by
  case o.status when 'novo' then 0 when 'em_contato' then 1 when 'fechado' then 2 else 3 end,
  o.created_at desc;

-- Estatísticas do admin, agora incluindo a loja
create or replace function public.get_admin_stats()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select case when not public.is_admin() then '{}'::jsonb else jsonb_build_object(
    'total_users',           (select count(*) from public.users where not is_admin),
    'active_users',          (select count(*) from public.users where not is_admin and not is_inactive),
    'inactive_users',        (select count(*) from public.users where not is_admin and is_inactive),
    'at_risk_users',         (select count(*) from public.users where not is_admin and not is_inactive and inactive_streak >= 2),
    'pending_cancellations', (select count(*) from public.sales where status = 'pendente_cancelamento'),
    'pending_prizes',        (select count(*) from public.prize_requests where status = 'solicitado'),
    'sales_this_month',      (select coalesce(sum(quantity), 0) from public.sales
                               where status = 'ativa'
                                 and date_trunc('month', sold_at) = date_trunc('month', now())),
    'points_this_month',     (select coalesce(sum(points), 0) from public.points_ledger
                               where level = 0
                                 and date_trunc('month', created_at) = date_trunc('month', now())),
    'open_orders',           (select count(*) from public.orders where status in ('novo', 'em_contato')),
    'new_orders',            (select count(*) from public.orders where status = 'novo'),
    'orders_revenue_month',  (select coalesce(sum(total_cents), 0) from public.orders
                               where status = 'fechado'
                                 and date_trunc('month', closed_at) = date_trunc('month', now())),
    'active_products',       (select count(*) from public.products where is_active),
    'total_customers',       (select count(*) from public.customers)
  ) end;
$$;

grant execute on function public.get_admin_stats() to authenticated;

