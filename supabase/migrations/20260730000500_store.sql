  add column if not exists product_id uuid references public.products (id) on delete set null;

create index if not exists sales_order_id_idx on public.sales (order_id);

-- =============================================================
-- Estorno de pontos de uma venda (extraído para ser reutilizado
-- pelo cancelamento de venda e pelo cancelamento de pedido fechado)
-- =============================================================
create or replace function public.fn_reverse_sale_points(p_sale_id uuid)
returns int
language sql
security definer
set search_path = public
as $$
  with inserted as (
    insert into public.points_ledger
      (user_id, source_user_id, origin, base_points, multiplier, level,
       sale_id, is_reversal, reverses_id, description)
    select l.user_id, l.source_user_id, l.origin, -l.base_points, l.multiplier, l.level,
           l.sale_id, true, l.id, 'Estorno de venda cancelada'
    from public.points_ledger l
    where l.sale_id = p_sale_id
      and not l.is_reversal
      and not exists (select 1 from public.points_ledger r where r.reverses_id = l.id)
    returning 1
  )
  select count(*)::int from inserted;
$$;

-- review_sale_cancellation passa a usar o helper
create or replace function public.review_sale_cancellation(
  p_sale_id uuid,
  p_approve boolean
)
returns public.sales
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sale public.sales;
begin
  if not public.is_admin() then
    raise exception 'Apenas administradores podem revisar cancelamentos';
  end if;

  select * into v_sale from public.sales where id = p_sale_id for update;

  if v_sale.id is null then
    raise exception 'Venda não encontrada';
  end if;

  if v_sale.status <> 'pendente_cancelamento' then
    raise exception 'Esta venda não está aguardando revisão de cancelamento';
  end if;

  if p_approve then
    perform public.fn_reverse_sale_points(p_sale_id);

    update public.sales
       set status = 'cancelada', cancelled_at = now(), reviewed_by = auth.uid()
     where id = p_sale_id
    returning * into v_sale;
  else
    update public.sales
       set status = 'ativa', cancel_reason = null,
           cancel_requested_at = null, reviewed_by = auth.uid()
     where id = p_sale_id
    returning * into v_sale;
  end if;

  return v_sale;
end;
$$;

-- =============================================================
-- CLIENTE: registrar pedido
-- p_items: [{"product_id": "uuid", "quantity": 2}, ...]
-- Preço e pontos vêm sempre do catálogo, nunca do cliente.
-- =============================================================
create or replace function public.place_order(
  p_items    jsonb,
  p_phone    text,
  p_address  text default null,
  p_notes    text default null,
  p_ref      text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_customer  public.customers;
  v_order_id  uuid;
  v_number    bigint;
  v_ref       uuid;
  v_count     int;
  v_total     int;
  v_points    int;
begin
  select * into v_customer from public.customers where id = auth.uid();
  if v_customer.id is null then
    raise exception 'Crie uma conta de cliente para finalizar o pedido';
  end if;

  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'O carrinho está vazio';
  end if;

  if jsonb_array_length(p_items) > 50 then
    raise exception 'Máximo de 50 itens diferentes por pedido';
  end if;

  if coalesce(btrim(p_phone), '') = '' then
    raise exception 'Informe um telefone para o contato do pedido';
  end if;

  -- afiliado do link usado agora; se não vier, o que trouxe o cliente
  if p_ref is not null then
    select id into v_ref from public.users where username = lower(btrim(p_ref));
  end if;
  v_ref := coalesce(v_ref, v_customer.referred_by);

  insert into public.orders
    (customer_id, contact_name, contact_phone, contact_email, address, customer_notes, referred_by)
  values
    (v_customer.id, v_customer.full_name, btrim(p_phone), v_customer.email,
     coalesce(nullif(btrim(coalesce(p_address, '')), ''), v_customer.address),
     nullif(btrim(coalesce(p_notes, '')), ''), v_ref)
  returning id, order_number into v_order_id, v_number;

  -- monta os itens a partir do catálogo ativo
  with req as (
    select (item ->> 'product_id')::uuid as product_id,
           greatest(1, least(999, coalesce((item ->> 'quantity')::int, 1))) as quantity
    from jsonb_array_elements(p_items) item
  ),
  ins as (
    insert into public.order_items
      (order_id, product_id, product_name, quantity, unit_price_cents, unit_points)
    select v_order_id, p.id, p.name, r.quantity, p.price_cents, p.points_value
    from req r
    join public.products p on p.id = r.product_id and p.is_active
    returning quantity, unit_price_cents, unit_points
  )
  select count(*)::int,
         coalesce(sum(quantity * unit_price_cents), 0)::int,
         coalesce(sum(quantity * unit_points), 0)::int
    into v_count, v_total, v_points
  from ins;

  if v_count = 0 then
    raise exception 'Nenhum produto válido no carrinho';
  end if;

  update public.orders
     set total_cents = v_total, total_points = v_points
   where id = v_order_id;

  return jsonb_build_object(
    'order_id', v_order_id,
    'order_number', v_number,
    'items', v_count,
    'total_cents', v_total,
    'total_points', v_points
  );
end;
$$;

-- =============================================================
-- ADMIN: tocar o pedido
-- =============================================================
create or replace function public.mark_order_contacted(
  p_order_id uuid,
  p_notes    text default null
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders;
begin
  if not public.is_admin() then
    raise exception 'Apenas administradores podem atualizar pedidos';
  end if;

  update public.orders
     set status = 'em_contato',
         contacted_at = coalesce(contacted_at, now()),
         admin_notes = coalesce(p_notes, admin_notes),
         reviewed_by = auth.uid()
   where id = p_order_id
     and status in ('novo', 'em_contato')
  returning * into v_order;

  if v_order.id is null then
    raise exception 'Pedido não encontrado ou já finalizado';
  end if;

  return v_order;
end;
$$;

-- Fechar a venda: gera UMA venda por item, para que a contagem de
-- produtos da ativação mensal e os pontos fiquem ambos corretos.
-- Cada insert em sales dispara o motor de pontos já existente
-- (peso 1x + compressão dinâmica até o 5º nível).
create or replace function public.close_order(
  p_order_id uuid,
  p_notes    text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders;
  v_sales int := 0;
begin
  if not public.is_admin() then
    raise exception 'Apenas administradores podem fechar pedidos';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;

  if v_order.id is null then
    raise exception 'Pedido não encontrado';
  end if;

  if v_order.status = 'fechado' then
    raise exception 'Pedido já está fechado';
  end if;

  if v_order.status = 'cancelado' then
    raise exception 'Pedido cancelado não pode ser fechado';
  end if;

  if v_order.referred_by is not null then
    with created as (
      insert into public.sales
        (user_id, product_name, quantity, base_points, customer_name,
         notes, order_id, product_id)
      select v_order.referred_by, i.product_name, i.quantity, i.unit_points,
             v_order.contact_name,
             format('Pedido #%s da loja', v_order.order_number),
             v_order.id, i.product_id
      from public.order_items i
      where i.order_id = p_order_id
      returning 1
    )
    select count(*)::int into v_sales from created;
  end if;

  update public.orders
     set status = 'fechado',
         closed_at = now(),
         admin_notes = coalesce(p_notes, admin_notes),
         reviewed_by = auth.uid()
   where id = p_order_id;

  return jsonb_build_object(
    'order_id', p_order_id,
    'sales_created', v_sales,
    'points_distributed', v_order.referred_by is not null,
    'total_points', v_order.total_points
  );
end;
$$;

-- Cancelar. Se o pedido já estava fechado, estorna os pontos que ele
-- injetou na rede e marca as vendas geradas como canceladas.
create or replace function public.cancel_order(
  p_order_id uuid,
  p_notes    text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order    public.orders;
  v_sale     record;
  v_reversed int := 0;
begin
  if not public.is_admin() then
    raise exception 'Apenas administradores podem cancelar pedidos';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;

  if v_order.id is null then
    raise exception 'Pedido não encontrado';
  end if;

  if v_order.status = 'cancelado' then
    raise exception 'Pedido já está cancelado';
  end if;

  if v_order.status = 'fechado' then
    for v_sale in
      select id from public.sales
      where order_id = p_order_id and status <> 'cancelada'
    loop
      v_reversed := v_reversed + public.fn_reverse_sale_points(v_sale.id);
      update public.sales
         set status = 'cancelada', cancelled_at = now(), reviewed_by = auth.uid()
       where id = v_sale.id;
    end loop;
  end if;

  update public.orders
     set status = 'cancelado',
         cancelled_at = now(),
         admin_notes = coalesce(p_notes, admin_notes),
         reviewed_by = auth.uid()
   where id = p_order_id;

  return jsonb_build_object('order_id', p_order_id, 'ledger_rows_reversed', v_reversed);
end;
$$;

-- =============================================================
-- Signup: decide entre afiliado e cliente pelo metadata
-- =============================================================
create or replace function public.fn_handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sponsor  uuid;
  v_username text;
  v_role     text := lower(coalesce(new.raw_user_meta_data ->> 'role', 'affiliate'));
begin
  select id into v_sponsor
  from public.users
  where username = lower(new.raw_user_meta_data ->> 'sponsor_username');

  -- cliente da loja: não entra na árvore de afiliados
  if v_role = 'customer' then
    insert into public.customers (id, full_name, email, phone, referred_by)
    values (
      new.id,
      coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)),
      new.email,
      new.raw_user_meta_data ->> 'phone',
      v_sponsor
    );
    return new;
  end if;

  v_username := lower(coalesce(
    new.raw_user_meta_data ->> 'username',
    split_part(new.email, '@', 1)
  ));
  v_username := regexp_replace(v_username, '[^a-z0-9._-]', '', 'g');

  if length(v_username) < 3 then
    v_username := 'user' || substr(replace(new.id::text, '-', ''), 1, 8);
  end if;

  if exists (select 1 from public.users where username = v_username) then
    v_username := v_username || substr(replace(new.id::text, '-', ''), 1, 6);
  end if;

  insert into public.users (id, sponsor_id, username, full_name, email)
  values (
    new.id,
    v_sponsor,
    v_username,
    coalesce(new.raw_user_meta_data ->> 'full_name', v_username),
    new.email
  );

  return new;
end;
$$;

